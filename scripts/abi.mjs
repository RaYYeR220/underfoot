// Copies contract ABIs from the Foundry build into the SDK as typed `as const` modules.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages/sdk/src/abi");
mkdirSync(out, { recursive: true });

const contracts = {
  Underfoot: "underfootAbi",
  Ballot: "ballotAbi",
  Intake: "intakeAbi",
  UnderfootHook: "hookAbi",
  UnderfootPaymaster: "paymasterAbi",
  UnderfootLens: "lensAbi",
};

const index = [];
for (const [name, exportName] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"));
  const file = name.replace(/^Underfoot(.)/, (_, c) => c.toLowerCase()).replace(/^Underfoot$/, "underfoot");
  const fileName = name === "Underfoot" ? "underfoot" : file.charAt(0).toLowerCase() + file.slice(1);
  writeFileSync(
    join(out, `${fileName}.ts`),
    `// Generated by scripts/abi.mjs from contracts/out. Do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${exportName} } from "./${fileName}.js";`);
}
writeFileSync(join(out, "index.ts"), index.join("\n") + "\n");
console.log(`wrote ${index.length} ABIs to packages/sdk/src/abi`);
